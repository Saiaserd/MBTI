    <div class="intro-text">
        <h2>《心理類型》——MBTI 的起點</h2>
        <p>1921 年，榮格（Carl Jung）出版了一本書，名為《心理類型》（<em>Psychologische Typen</em>）。</p>
        <p>書中試圖回答一個核心問題：</p>
        <blockquote class="jung-quote">「為什麼人類對同一件事，會有不同的理解方式？」</blockquote>
    </div>
</div>

<div class="jung-content">
    <!-- 1. 能量流向 -->
    <section class="jung-section">
        <h3><span class="step-num">1</span>能量流向（態度 Attitude）</h3>
        <p>榮格一開始的分類只有兩大塊，第一塊是能量的流向：</p>
        <div class="jung-pair">
            <div class="jung-item">
                <span class="tag tag-e">E</span>
                <strong>外向 Extraversion</strong>
                <p>能量指向外界（人、事、刺激）。</p>
            </div>
            <div class="jung-item">
                <span class="tag tag-i">I</span>
                <strong>內向 Introversion</strong>
                <p>能量指向內在（思考、意義、主觀世界）。</p>
            </div>
        </div>
        <p class="jung-note">這裡的外向／內向，<strong>不是</strong>社交能力、<strong>不是</strong>話多話少，而是「人在處理世界時，重心放在哪裡」。</p>
    </section>

    <!-- 2. 四種心理功能 -->
    <section class="jung-section">
        <h3><span class="step-num">2</span>四種心理功能（Psychological Functions）</h3>
        <div class="jung-func-group">
            <h4>理性功能（Judging / Rational）</h4>
            <div class="jung-pair">
                <div class="jung-item">
                    <span class="tag tag-fn">T</span>
                    <strong>思考 Thinking</strong>
                    <p>用邏輯、因果、結構來判斷。</p>
                </div>
                <div class="jung-item">
                    <span class="tag tag-fn">F</span>
                    <strong>情感 Feeling</strong>
                    <p>用價值、好壞、人際影響來判斷。</p>
                </div>
            </div>
        </div>
        <div class="jung-func-group">
            <h4>非理性功能（Perceiving / Irrational）</h4>
            <div class="jung-pair">
                <div class="jung-item">
                    <span class="tag tag-fn">S</span>
                    <strong>感覺 Sensation</strong>
                    <p>感知實際存在的事物（五感）。</p>
                </div>
                <div class="jung-item">
                    <span class="tag tag-fn">N</span>
                    <strong>直覺 Intuition</strong>
                    <p>感知可能性、意象、未來走向。</p>
                </div>
            </div>
        </div>
    </section>

    <!-- 3. 8 種心理型態 -->
    <section class="jung-section">
        <h3><span class="step-num">3</span>8 種心理型態</h3>
        <p>榮格把「內向／外向」<strong>×</strong>「四種功能」交叉，得到了 8 種心理型態：</p>
        <ul class="jung-types">
            <li>內向／外向 — 思考型（T）</li>
            <li>內向／外向 — 情感型（F）</li>
            <li>內向／外向 — 感覺型（S）</li>
            <li>內向／外向 — 直覺型（N）</li>
        </ul>
    </section>

    <!-- 4. 主功能與劣勢功能 -->
    <section class="jung-section">
        <h3><span class="step-num">4</span>主功能與劣勢功能</h3>
        <p>榮格不相信「完整平衡的人」。他認為每個人一定會偏重一個<strong>主功能</strong>，而另一個功能會被壓到潛意識。</p>
        <p>被壓抑的功能，往往會變成<strong>最不成熟、最容易失控</strong>的地方。</p>
        <div class="jung-pair">
            <div class="jung-item arrow">主直覺 <span>→</span> 劣勢感覺</div>
            <div class="jung-item arrow">主思考 <span>→</span> 劣勢情感</div>
        </div>
    </section>

    <!-- 5. 從理論到 MBTI -->
    <section class="jung-section">
        <h3><span class="step-num">5</span>從理論到 MBTI</h3>
        <p>二戰期間，Katharine Cook Briggs 與 Isabel Briggs Myers 母女做了三件事：</p>
        <ol class="jung-steps">
            <li>把理論改寫成問卷</li>
            <li>加上 J / P 這個維度</li>
            <li>把「心理動態」變成「類型標籤」</li>
        </ol>
        <p class="jung-formula">榮格哲學 ＋ 美國實用主義 ＋ 戰爭時期人力配置需求 ＝ <strong>MBTI 16 型人格</strong></p>
    </section>

    <!-- 結語 -->
    <section class="jung-section jung-epilogue">
        <p>而 MBTI 也在近 20 年因網路的發展，用獨特的性格與顏色鮮明的人物，創造出強大的渲染力，在網路世界四處遊走；卻也被部分人加以改造。這種「貼標籤」的行為，讓最原始的「榮格心理類型」，逐漸變成了「16 人格的刻板印象」。</p>
    </section>
